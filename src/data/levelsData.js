export function getLevelInfo(xp = 100) {
  const safeXp = Math.max(0, Number(xp) || 0);
  const level = Math.min(50, 1 + Math.floor(safeXp / 120));
  const title = LEVEL_TITLES[level - 1] || LEVEL_TITLES[0];
  const currentLevelStartXp = (level - 1) * 120;
  const nextLevelXp = level * 120;
  const progressPct = level === 50 ? 100 : Math.min(100, Math.round(((safeXp - currentLevelStartXp) / 120) * 100));

  // Аватарная рамка зависит от уровня (1-50)
  let frameClass = 'ring-2 ring-zinc-600';
  let frameName = 'Базовая сталь';
  if (level >= 40) {
    frameClass = 'ring-4 ring-[#FFAA00] shadow-[0_0_20px_rgba(255,170,0,0.6)]';
    frameName = 'Золото Самотлора';
  } else if (level >= 25) {
    frameClass = 'ring-4 ring-purple-500 shadow-[0_0_16px_rgba(168,85,247,0.5)]';
    frameName = 'Неоновый плазмоид';
  } else if (level >= 15) {
    frameClass = 'ring-3 ring-[#22D3EE] shadow-[0_0_12px_rgba(34,211,238,0.4)]';
    frameName = 'Криогенный титан';
  } else if (level >= 5) {
    frameClass = 'ring-2 ring-[#00C853] shadow-[0_0_10px_rgba(0,200,83,0.3)]';
    frameName = 'Изумрудная тайга';
  }

  return {
    level,
    title,
    xp: safeXp,
    nextLevelXp,
    progressPct,
    frameClass,
    frameName
  };
}